"""Create a new pure-Blueprint copy with no NodeForge search path or plugin files."""
import hashlib, json, shutil
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = root / 'ValidationProject/Content'
target = (root / 'ValidationProject/StandaloneChecks/NodeForgeStandalone').resolve()
assert target.is_relative_to(root.resolve()) and not target.exists()
target.mkdir(parents=True, exist_ok=False)
shutil.copytree(source, target / 'Content')
project = target / 'NodeForgeStandalone.uproject'
project.write_text(json.dumps({'FileVersion': 3, 'EngineAssociation': '5.3',
    'Description': 'Independent native asset delivery check; generation plugin disabled and absent',
    'Plugins': [{'Name': 'NodeForge', 'Enabled': False}]}, indent=2), 'utf-8')
(target / 'Config').mkdir()
# Purpose-built settings avoid unrelated autogenerated machine-specific config and credentials.
(target / 'Config/DefaultEngine.ini').write_text('''[/Script/EngineSettings.GameMapsSettings]
GameDefaultMap=/Game/NodeForgeTests/NFVisualGallery
EditorStartupMap=/Game/NodeForgeTests/NFVisualGallery

[/Script/WindowsTargetPlatform.WindowsTargetSettings]
DefaultGraphicsRHI=DefaultGraphicsRHI_DX11
+D3D11TargetedShaderFormats=PCD3D_SM5

[/Script/Engine.RendererSettings]
r.DynamicGlobalIlluminationMethod=0
r.ReflectionMethod=0
r.RayTracing=False
r.DefaultFeature.AutoExposure=False
r.AntiAliasingMethod=0
''', 'utf-8')
(target / 'Config/DefaultGame.ini').write_text('''[/Script/UnrealEd.ProjectPackagingSettings]
BuildConfiguration=PPBC_Development
bCookAll=False
bUsePakFile=True
bUseIoStore=False
+MapsToCook=(FilePath="/Game/NodeForgeTests/NFVisualGallery")
''', 'utf-8')
assets = []
for path in sorted(source.rglob('*')):
    if not path.is_file():
        continue
    copied = target / 'Content' / path.relative_to(source)
    before = hashlib.sha256(path.read_bytes()).hexdigest()
    after = hashlib.sha256(copied.read_bytes()).hexdigest()
    assert before == after
    assets.append({'source': path.relative_to(root).as_posix(), 'copy': copied.relative_to(root).as_posix(), 'sha256': before})
assert not (target / 'Plugins').exists()
receipt = {'result': 'prepared', 'project': project.relative_to(root).as_posix(),
    'pluginEnabled': False, 'additionalPluginDirectories': [], 'pluginFilesPresent': False,
    'assets': assets, 'scope': 'Copy only Content and safe native configuration; original projects unchanged; execution and packaging not yet validated'}
out = root / 'Reports/20261008UsablePrototype/StandalonePreparation.json'
with out.open('x', encoding='utf-8') as f:
    json.dump(receipt, f, indent=2)
print('Prepared independent copy; copied assets hash-matched:', len(assets))
