import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
export const runtimeSources = ['ThemeController.js', 'ArticleController.js', 'ReadingController.js', 'NavigationController.js', 'Scrollbars.js'].map(name => 'Runtime/' + name);

// One classic-script output keeps both file:// documents and hosted pages working.
// Feature state stays private; only theme-aware links cross a feature boundary.
export function buildTheme() {
  const modules = runtimeSources.map(name => fs.readFileSync(path.join(root, name), 'utf8'));
  return {
    'Theme.js': '/* Generated by BuildTheme.mjs. Edit Runtime sources. */\n(() => {\n\'use strict\';\n' + modules.join('\n') + '\nconst {syncThemeLink} = initializeTheme();\ninitializeArticle();\ninitializeReading();\ninitializeNavigation(syncThemeLink);\ninitializeScrollbars();\n})();\n',
    'Theme.css': fs.readFileSync(path.join(root, 'Theme.css'), 'utf8') + '\n' + fs.readFileSync(path.join(root, 'Runtime/Scrollbars.css'), 'utf8')
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 4 || process.argv[2] !== '--output') throw Error('Usage: node BuildTheme.mjs --output <assets-directory>');
  const output = path.resolve(process.argv[3]);
  fs.mkdirSync(output, {recursive:true});
  for (const [name, content] of Object.entries(buildTheme())) fs.writeFileSync(path.join(output, name), content);
}
